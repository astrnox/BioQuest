def sanitize(s):
    s = s.replace("\u207a", "+").replace("\u207b", "-")
    s = s.replace("\uff08", "(").replace("\uff09", ")")
    s = s.replace("\uff0c", ",").replace("\uff1a", ":")
    s = s.replace("\u3001", ",").replace("\u2014", "-")
    return s

def mkq(stem, opts, ans, analysis, discipline, tag, kn_point):
    stem = sanitize(stem); opts = {k: sanitize(v) for k,v in opts.items()}
    analysis = sanitize(analysis); kn_point = sanitize(kn_point)
    assert len(stem) >= 15
    for k in "ABCD": assert k in opts
    assert ans in "ABCD"
    assert len(analysis) >= 150, f"analysis too short ({len(analysis)})"
    return {"stem":stem,"options":opts,"answer":ans,"analysis":analysis,
            "knowledge":[discipline,tag,kn_point],"module":"module_2",
            "difficulty":"league","target":"both","concept":tag}

def P(tag, stem, opts, ans, analysis, kn):
    return mkq(stem, opts, ans, analysis, "植物学", tag, kn)

