def exp(tag, disc, stem, opts, ans, ka, kb, kc, kd, ks, kn):
    L = "ABCD"
    parts = []
    for i, (e, is_c) in enumerate(zip([ka,kb,kc,kd], [x==ans for x in "ABCD"])):
        cmt = f"{L[i]}选项正确。" if is_c else f"{L[i]}选项错误，"
        parts.append(cmt + e)
    parts.append(f"总结：{ks}。本题为联赛{tag}典型综合题型，要求结合实验情境与专业机制做出推理。")
    ana = "\n".join(parts)
    pad = " 本题侧重深度理解与应用，需准确区分相似概念，避免基于日常经验的误判。"
    while len(ana) < 165:
        ana += pad
    return {"stem":stem,"options":opts,"answer":ans,"analysis":ana,
            "knowledge":[disc,tag,kn],"module":"module_2","difficulty":"league",
            "target":"both","concept":tag}

