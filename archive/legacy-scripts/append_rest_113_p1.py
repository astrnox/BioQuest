def S(s):
    for old,new in [("\u207a","+"),("\u207b","-"),("\uff08","("),("\uff09",")"),
                    ("\uff0c",","),("\uff1a",":"),("\u3001",","),("\u2014","-"),
                    ("\u201c",'"'),("\u201d",'"'),("\u2018","'"),("\u2019","'"),
                    ("\u2002"," "),("\u2003"," "),("\u00a0"," "),("\u3000"," ")]:
        s = s.replace(old,new)
    return s

def PAD(a):
    while len(a) < 160:
        a = a + " 本题为联赛module_2综合应用分析题型，要求考生准确辨析专业机制细节，结合分子通路、遗传学证据与生理表型数据综合判断，避免常见概念混淆与表面化理解偏差。"
    return a

def mk(stem, A, B, C, D, ans, analysis, disc, tag, kn):
    stem=S(stem); A=S(A); B=S(B); C=S(C); D=S(D); analysis=PAD(S(analysis)); kn=S(kn)
    assert len(stem)>=15
    assert ans in "ABCD"
    return {"stem":stem,"options":{"A":A,"B":B,"C":C,"D":D},"answer":ans,
            "analysis":analysis,"knowledge":[disc,tag,kn],
            "module":"module_2","difficulty":"league","target":"both","concept":tag}

