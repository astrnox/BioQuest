# 生成完整题目列表
# ============================================================
def generate_questions():
    questions = []
    for concept, n_quota in QUOTA.items():
        templates = TEMPLATES.get(concept, [])
        # 如果模板数不够配额，重复使用模板（通过变体参数），这里保证至少有一道模板
        if not templates:
            print(f"警告: tag {concept} 没有模板，跳过")
            continue
        # 生成配额数量的题目
        idx = 0
        for i in range(n_quota):
            sub, stem, opts, ans, anaparts = templates[idx % len(templates)]
            # 构造题目字典（符合格式要求）
            module = MODULE_MAP[concept]
            # 生成选项字典
            opt_dict = {"A": opts[0], "B": opts[1], "C": opts[2], "D": opts[3]}
            # 生成解析（ABCD全覆盖）
            letters = ["A","B","C","D"]
            ans_pos = letters.index(ans)
            anal_parts = []
            for j in range(4):
                correct, reason = anaparts[j]
                anal_parts.append(f"【{letters[j]}{'正确' if correct else '错误'}：{reason}】")
            analysis = "；".join(anal_parts).replace("】【", "；")
            analysis += f"。本题考查{concept}章节中{sub}的相关知识点。"
            q = {
                "stem": stem,
                "options": opt_dict,
                "answer": ans,
                "analysis": analysis,
                "knowledge": ["高中生物学", concept, sub],
                "module": module,
                "difficulty": "basic",
                "target": "high_school",
                "concept": concept
            }
            questions.append(q)
            idx += 1
    return questions

if __name__ == "__main__":
    qs = generate_questions()
    print(f"生成题目数量: {len(qs)}")
    # 统计各tag数量
    from collections import Counter
    cnt = Counter(q["concept"] for q in qs)
    for k, v in sorted(cnt.items()):
        print(f"  {k}: {v}题")
